-- OBJECTIVE QUESTION 9
-- Products with increase/decrease in sales over the years?
-- =============================================================

WITH YearlySales AS (
    SELECT
        Product,
        YEAR(OrderDate) AS Year,
        SUM([Sale Price]) AS Revenue
    FROM Orders
    GROUP BY Product, YEAR(OrderDate)
),
YOY AS (
    SELECT
        a.Product,
        a.Year,
        a.Revenue AS Current_Revenue,
        b.Revenue AS Prev_Revenue,
        ROUND(((a.Revenue - b.Revenue) / NULLIF(b.Revenue, 0)) * 100, 2) AS YOY_Growth_Pct
    FROM YearlySales a
    LEFT JOIN YearlySales b
        ON a.Product = b.Product AND a.Year = b.Year + 1
)
SELECT *
FROM YOY
WHERE Prev_Revenue IS NOT NULL
ORDER BY Product, Year;

-- Insight: Most products showed steady performance 2015-2019, with a
-- significant spike in 2020, correlating with the pandemic-driven demand
-- surge for home electronics and health products.


