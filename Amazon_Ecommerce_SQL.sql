-- OBJECTIVE QUESTION 20
-- Top 3 product categories with highest sales increase (past vs previous year) (SQL)
-- =============================================================

WITH CategoryYearlySales AS (
    SELECT
        [Product Category],
        YEAR(OrderDate) AS Year,
        SUM([Sale Price]) AS Revenue
    FROM Orders
    GROUP BY [Product Category], YEAR(OrderDate)
),
YOY AS (
    SELECT
        a.[Product Category],
        a.Year,
        a.Revenue AS Current_Year_Revenue,
        b.Revenue AS Prev_Year_Revenue,
        ROUND(((a.Revenue - b.Revenue) / NULLIF(b.Revenue, 0)) * 100, 2) AS YOY_Growth_Pct
    FROM CategoryYearlySales a
    INNER JOIN CategoryYearlySales b
        ON a.[Product Category] = b.[Product Category]
        AND a.Year = b.Year + 1
    WHERE a.Year = (SELECT MAX(Year) FROM Orders)
)
SELECT TOP 3
    [Product Category],
    ROUND(Current_Year_Revenue, 2) AS Latest_Year_Revenue,
    ROUND(Prev_Year_Revenue, 2)    AS Prior_Year_Revenue,
    YOY_Growth_Pct
FROM YOY
ORDER BY YOY_Growth_Pct DESC;

-- Output: Top 3 categories by YoY growth in the most recent year (2020 vs 2019).
-- Insight: Categories surging in 2020 reflect pandemic consumer behaviour —
-- Health & Beauty and Electronics/Phones saw the highest YoY growth,
-- presenting opportunities for targeted inventory and marketing investment.

