-- OBJECTIVE QUESTION 16
-- Rolling 3-month average revenue by product category (SQL)
-- =============================================================

WITH MonthlyCatRevenue AS (
    SELECT
        [Product Category],
        YEAR(OrderDate)  AS Year,
        MONTH(OrderDate) AS Month,
        SUM([Sale Price]) AS Monthly_Revenue
    FROM Orders
    GROUP BY [Product Category], YEAR(OrderDate), MONTH(OrderDate)
)
SELECT
    [Product Category],
    Year,
    Month,
    ROUND(Monthly_Revenue, 2) AS Monthly_Revenue,
    ROUND(AVG(Monthly_Revenue) OVER (
        PARTITION BY [Product Category]
        ORDER BY Year, Month
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ), 2) AS Rolling_3Month_Avg
FROM MonthlyCatRevenue
ORDER BY [Product Category], Year, Month;

-- Insight: Phones & Tablets and Electronics maintain the highest rolling
-- averages. The 3-month smoothing removes seasonality noise and clearly
-- shows the 2020 upward trend across all categories.


