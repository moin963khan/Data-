-- OBJECTIVE QUESTION 19
-- Customers with revenue > 30% above average revenue per customer (SQL)
-- =============================================================

WITH CustomerRevenue AS (
    SELECT
        CustomerID,
        SUM([Sale Price]) AS Total_Revenue
    FROM Orders
    GROUP BY CustomerID
),
AvgRevenue AS (
    SELECT AVG(Total_Revenue) AS Avg_Customer_Revenue FROM CustomerRevenue
)
SELECT
    cr.CustomerID,
    ROUND(cr.Total_Revenue, 2) AS Total_Revenue,
    ROUND(ar.Avg_Customer_Revenue, 2) AS Avg_Revenue,
    ROUND(((cr.Total_Revenue - ar.Avg_Customer_Revenue) / ar.Avg_Customer_Revenue) * 100, 2) AS Pct_Above_Avg
FROM CustomerRevenue cr
CROSS JOIN AvgRevenue ar
WHERE cr.Total_Revenue > ar.Avg_Customer_Revenue * 1.30
ORDER BY cr.Total_Revenue DESC;

-- Insight: High-value outlier customers represent key accounts deserving
-- personalised account management and exclusive early access to new products.


