-- OBJECTIVE QUESTION 15
-- Month-over-month revenue growth rate (SQL)
-- =============================================================

WITH MonthlyRevenue AS (
    SELECT
        YEAR(OrderDate)  AS Year,
        MONTH(OrderDate) AS Month,
        SUM([Sale Price]) AS Total_Revenue
    FROM Orders
    GROUP BY YEAR(OrderDate), MONTH(OrderDate)
),
MOM AS (
    SELECT
        Year,
        Month,
        Total_Revenue,
        LAG(Total_Revenue) OVER (ORDER BY Year, Month) AS Prev_Month_Revenue
    FROM MonthlyRevenue
)
SELECT
    Year,
    Month,
    ROUND(Total_Revenue, 2)      AS Total_Revenue,
    ROUND(Prev_Month_Revenue, 2) AS Prev_Month_Revenue,
    ROUND(((Total_Revenue - Prev_Month_Revenue) / NULLIF(Prev_Month_Revenue, 0)) * 100, 2) AS MOM_Growth_Pct
FROM MOM
ORDER BY Year, Month;

-- Insight: Revenue shows seasonal patterns with strong January performance
-- and dips around Q3 (Sept). 2020 saw exceptionally high MoM growth in H1
-- driven by pandemic-related demand surge.


