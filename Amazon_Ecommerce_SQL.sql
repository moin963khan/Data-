-- OBJECTIVE QUESTION 2
-- How will you get the "Customer's" ages in the "Order" tables
-- according to customer IDs?
-- =============================================================

SELECT
    o.OrderID,
    o.CustomerID,
    c.[Customer Age],
    c.[Customer Gender],
    o.OrderDate,
    o.[Sale Price]
FROM Orders o
LEFT JOIN Customers c ON o.CustomerID = c.CustomerID
ORDER BY o.OrderID;

-- Insight: By performing a LEFT JOIN on CustomerID, we enrich the Orders
-- table with customer demographics. This allows age-based segmentation of
-- purchasing behaviour.


