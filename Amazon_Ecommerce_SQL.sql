-- OBJECTIVE QUESTION 14
-- Top 5 most valuable customers using composite score (SQL)
-- =============================================================

WITH CustomerMetrics AS (
    SELECT
        CustomerID,
        SUM([Sale Price])              AS Total_Revenue,
        COUNT(OrderID)                 AS Order_Frequency,
        AVG([Sale Price])              AS Avg_Order_Value
    FROM Orders
    GROUP BY CustomerID
),
Normalized AS (
    SELECT
        CustomerID,
        Total_Revenue,
        Order_Frequency,
        Avg_Order_Value,
        -- Normalize each metric to 0-1 scale
        (Total_Revenue   - MIN(Total_Revenue)   OVER()) / NULLIF((MAX(Total_Revenue)   OVER() - MIN(Total_Revenue)   OVER()), 0) AS Rev_Score,
        (Order_Frequency - MIN(Order_Frequency) OVER()) / NULLIF((MAX(Order_Frequency) OVER() - MIN(Order_Frequency) OVER()), 0) AS Freq_Score,
        (Avg_Order_Value - MIN(Avg_Order_Value) OVER()) / NULLIF((MAX(Avg_Order_Value) OVER() - MIN(Avg_Order_Value) OVER()), 0) AS AOV_Score
    FROM CustomerMetrics
),
ScoredCustomers AS (
    SELECT
        CustomerID,
        Total_Revenue,
        Order_Frequency,
        ROUND(Avg_Order_Value, 2)                                       AS Avg_Order_Value,
        ROUND((Rev_Score * 0.5) + (Freq_Score * 0.3) + (AOV_Score * 0.2), 4) AS Composite_Score
    FROM Normalized
)
SELECT TOP 5
    CustomerID,
    Total_Revenue,
    Order_Frequency,
    Avg_Order_Value,
    Composite_Score
FROM ScoredCustomers
ORDER BY Composite_Score DESC;

-- Output: Top 5 customers identified with highest composite scores
-- weighting revenue (50%), order frequency (30%), and AOV (20%).
-- Insight: These customers should be targeted for exclusive loyalty tier
-- benefits (e.g., Amazon Prime Gold membership with free express delivery
-- and personalised discount coupons).


