-- OBJECTIVE QUESTION 18
-- Average days between consecutive orders for customers with >= 5 orders (SQL)
-- =============================================================

WITH CustomerOrders AS (
    SELECT
        CustomerID,
        OrderDate,
        LAG(OrderDate) OVER (PARTITION BY CustomerID ORDER BY OrderDate) AS Prev_Order_Date
    FROM Orders
),
DaysBetween AS (
    SELECT
        CustomerID,
        DATEDIFF(DAY, Prev_Order_Date, OrderDate) AS Days_Between
    FROM CustomerOrders
    WHERE Prev_Order_Date IS NOT NULL
),
CustomerFreq AS (
    SELECT CustomerID
    FROM Orders
    GROUP BY CustomerID
    HAVING COUNT(OrderID) >= 5
)
SELECT
    ROUND(AVG(d.Days_Between), 2) AS Avg_Days_Between_Orders
FROM DaysBetween d
INNER JOIN CustomerFreq cf ON d.CustomerID = cf.CustomerID;

-- Insight: Analysing inter-order intervals helps design timely re-engagement
-- campaigns (e.g., send a nudge notification just before the typical
-- repurchase window closes).


